/**
 * Copies the food catalog, avoid pairs, food images and font into docs/ so the
 * landing page (docs/index.html) spins the same reels as the app.
 * Run after `npm run data:foods`: npm run web:landing
 */
import { copyFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import avoidPairs from '../src/data/avoidPairs.json';
import foods from '../src/data/foods.json';

const ROOT = resolve(__dirname, '..');
const OUT = resolve(ROOT, 'docs/assets');
const IMAGES = resolve(ROOT, 'assets/foods/atlas');

mkdirSync(resolve(OUT, 'foods'), { recursive: true });

const catalog = foods
  .filter((f) => f.enabled)
  .map((f) => {
    const image = resolve(IMAGES, `${f.imageKey}.webp`);
    if (existsSync(image)) copyFileSync(image, resolve(OUT, 'foods', `${f.imageKey}.webp`));
    return {
      id: f.id,
      name: f.name,
      category: f.category,
      image: existsSync(image) ? `assets/foods/${f.imageKey}.webp` : null,
      emoji: (f as { emoji?: string }).emoji ?? null,
    };
  });

copyFileSync(resolve(ROOT, 'assets/fonts/UncutSans-Variable.ttf'), resolve(OUT, 'UncutSans-Variable.ttf'));
copyFileSync(resolve(ROOT, 'assets/images/icon.png'), resolve(OUT, 'icon.png'));
writeFileSync(
  resolve(OUT, 'foods.js'),
  `// Generated by scripts/build-landing.ts — do not edit.\nwindow.FOOD_SLOT = ${JSON.stringify({ foods: catalog, avoid: avoidPairs })};\n`,
  'utf8',
);
console.log(`Landing: ${catalog.length} foods, ${avoidPairs.length} avoid pairs → docs/assets`);
